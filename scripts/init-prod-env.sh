#!/usr/bin/env bash
# Generate .env.prod for docker-compose.prod.yml with strong random secrets.
#
# Usage:
#   ./scripts/init-prod-env.sh                     # prompts for domain and Gemini key
#   DOMAIN=x GEMINI_API_KEY=y ./scripts/init-prod-env.sh
set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
ENV_FILE="$ROOT_DIR/.env.prod"

if [[ -f "$ENV_FILE" ]]; then
  echo ".env.prod already exists. Delete it first if you really want new secrets" >&2
  echo "(new database/storage passwords will NOT match existing volumes)." >&2
  exit 1
fi

DOMAIN="${DOMAIN:-}"
GEMINI_API_KEY="${GEMINI_API_KEY:-}"
[[ -n "$DOMAIN" ]] || read -rp "Domain (e.g. gradeai-yourname.duckdns.org): " DOMAIN
[[ -n "$GEMINI_API_KEY" ]] || read -rsp "Gemini API key (input hidden): " GEMINI_API_KEY && echo
DOMAIN="${DOMAIN#https://}"; DOMAIN="${DOMAIN#http://}"; DOMAIN="${DOMAIN%/}"

if [[ -z "$DOMAIN" || -z "$GEMINI_API_KEY" ]]; then
  echo "Domain and Gemini API key are both required." >&2
  exit 1
fi

secret() { openssl rand -hex "$1"; }

POSTGRES_PASSWORD="$(secret 24)"
MINIO_ROOT_USER="gradeai$(secret 4)"
MINIO_ROOT_PASSWORD="$(secret 24)"
REGISTRATION_CODE="$(secret 8)"

umask 077
cat > "$ENV_FILE" <<EOF
# Generated by scripts/init-prod-env.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ).
# Contains secrets. Never commit this file.

DOMAIN=${DOMAIN}

APP_ENV=production
DEBUG=false
CORS_ORIGINS=https://${DOMAIN}

POSTGRES_USER=gradeai
POSTGRES_PASSWORD=${POSTGRES_PASSWORD}
POSTGRES_DB=gradeai
DATABASE_URL=postgresql+asyncpg://gradeai:${POSTGRES_PASSWORD}@postgres:5432/gradeai
DATABASE_URL_SYNC=postgresql://gradeai:${POSTGRES_PASSWORD}@postgres:5432/gradeai

REDIS_URL=redis://redis:6379/0
CELERY_BROKER_URL=redis://redis:6379/1
CELERY_RESULT_BACKEND=redis://redis:6379/2

CHROMADB_HOST=chromadb
CHROMADB_PORT=8000

JWT_SECRET=$(secret 32)
# Share this only with people who should be able to sign up as professors.
PROFESSOR_REGISTRATION_CODE=${REGISTRATION_CODE}

GEMINI_API_KEY=${GEMINI_API_KEY}
GEMINI_MODEL=gemini-3.6-flash
GEMINI_FALLBACK_MODEL=gemini-3.5-flash-lite

MINIO_ROOT_USER=${MINIO_ROOT_USER}
MINIO_ROOT_PASSWORD=${MINIO_ROOT_PASSWORD}
AWS_ACCESS_KEY_ID=${MINIO_ROOT_USER}
AWS_SECRET_ACCESS_KEY=${MINIO_ROOT_PASSWORD}
AWS_REGION=us-east-1
AWS_S3_BUCKET=gradeai-uploads
AWS_S3_ENDPOINT=http://minio:9000
AWS_ENDPOINT_URL=http://minio:9000
AWS_S3_PUBLIC_ENDPOINT=https://${DOMAIN}

RATE_LIMIT_REGISTER_PER_HOUR=10
RATE_LIMIT_PRESIGN_PER_MINUTE=30
EOF

echo "Wrote $ENV_FILE (permissions 600)."
echo "Professor registration code: ${REGISTRATION_CODE}"
